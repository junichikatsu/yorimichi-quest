/**
 * ゲーム画面らしく見せるための、地図の塗り分け。
 *
 * 元のスタイル（streets-v12）の色は現実の地図として最適化されていて、彩度も明度も近い色が多い。
 * それを機械的にパレットへ丸めると、灰色と青緑ばかりの「潰れた地図」になる。
 * 近い色を探すのではなく、**地物ごとに色を決め打つ**必要がある。
 *
 * 選んでいるのはすべてファミコンのパレットにある色。最後の丸めでも変化しない。
 */
export const GAME_COLORS = {
  /** 地面。淡い砂色（$37） */
  land: '#fce0a8',
  /** 建物。地面より暗い金茶（$18） */
  building: '#ac7c00',
  /** 緑地（$1A） */
  green: '#00a800',
  /** 水面。空色（$21）。純青（$12）は面積が広いと目が疲れる */
  water: '#3cbcfc',
  /** 幹線道路。琥珀（$28）。彩度が高いので高速道路だけに絞って使う */
  roadMajor: '#f8b800',
  /** 生活道路。白（$30） */
  roadMinor: '#fcfcfc',
} as const

/**
 * 未踏エリアの色（＝暗いパレット）。
 *
 * ## なぜ市松模様をやめたか
 *
 * 実機に半透明は無く、市松模様で薄く見せていた。それに倣って 1 ドットおきに塗っていたが、
 * **画面いっぱいに 1 ドット周期の模様が出ると目がちらつく**。
 * 拡大時のドット格子と干渉して細かく明滅するためで、探索率 0% では画面全体がこれになる。
 *
 * ファミコンにはもう 1 つ、より穏やかな常套手段がある。**パレットの差し替え**で、
 * 同じ絵を暗い色の組で描いて夜や影を表した。こちらを使う。
 * 模様が出ないのでちらつかず、色みが残るので未踏エリアでも地図として読める。
 *
 * ## 対応表
 *
 * 基本は「元の色を暗くしていちばん近いパレット色」を機械的に選ぶ。
 * ただしそれだと色みが失われるものがあるので、下の 4 つだけ手で指定する。
 */
const SHADOW_OVERRIDES: Record<string, string> = {
  // 自動だと灰色に転ぶ。砂の色みは残したい
  [GAME_COLORS.land]: '#ac7c00',
  // 地面より暗くして、未踏エリアでも道の形が分かるようにする
  [GAME_COLORS.roadMajor]: '#503000',
  // 地面より明るい側で分ける。灰色にすると地面の金茶と色みがぶつかって、
  // 密な道路網が細かい縞に見えてしまうので、同じ暖色の系列から選ぶ
  [GAME_COLORS.roadMinor]: '#f8d878',
  // 自動だと紫へ転ぶ
  [GAME_COLORS.water]: '#0058f8',
}

/** 未踏エリアの色を決めるときに、元の色へ掛ける明るさ */
export const SHADOW_FACTOR = 0.65

/** 手で決めた対応。ここに無い色は SHADOW_FACTOR で機械的に暗くする */
export function shadowOverrideFor(hex: string): string | undefined {
  return SHADOW_OVERRIDES[hex]
}

/** 未踏エリアの見せ方。既定は暗いパレット */
export type FogStyle = 'shade' | 'dither'
